import { expect, it } from "vitest";
import { thermocoupleMillivolt } from "../src/simulation/controlLogic";
import { catalogById } from "../src/catalog/dolCatalog";
import { validateCircuit } from "../src/electrical/topology";
import { executeCircuitModels } from "../src/simulation/circuitModels";
import { evaluateFunctionalSignal } from "../src/simulation/functionalModels";
import type { CircuitDocument } from "../src/types/electrical";
import { applyReversingState, createReversingCircuit } from "../src/projects/reversingCircuit";
import { initialReversingState, transitionReversing } from "../src/simulation/reversingStarter";

// Independent rounded table entries, not values generated by our polynomial.
// NIST ITS-90 Type K table, reference junction 0 °C.
it.each([[-270, -6.458], [-200, -5.891], [-100, -3.554], [0, 0], [100, 4.096], [500, 20.644], [1000, 41.276], [1372, 54.886]])("matches the NIST table at %s °C", (temperature, millivolts) => {
  expect(Math.abs(thermocoupleMillivolt(temperature) - millivolts)).toBeLessThanOrEqual(.00051);
});

it("models both junctions, including equal and reversed junctions", () => {
  expect(thermocoupleMillivolt(100, 25)).toBeCloseTo(3.096, 3);
  expect(thermocoupleMillivolt(500, 500)).toBe(0);
  expect(thermocoupleMillivolt(-100, 100)).toBeCloseTo(-7.65, 3);
  expect(thermocoupleMillivolt(25, 100)).toBe(-thermocoupleMillivolt(100, 25));
});

it.each([-271, 1373, NaN, Infinity, -Infinity])("rejects unsupported temperature %s at either junction", (temperature) => {
  expect(() => thermocoupleMillivolt(temperature)).toThrow(RangeError);
  expect(() => thermocoupleMillivolt(20, temperature)).toThrow(RangeError);
});

it.each([true, "100", NaN, Infinity, 2000])("reports malformed/out-of-range placed sensor input %s as a signal fault", (value) => {
  expect(evaluateFunctionalSignal("sensor-thermocouple", { temperatureC: value })).toMatchObject({ value: false, error: expect.stringContaining("Type K") });
  expect(evaluateFunctionalSignal("sensor-thermocouple", { temperatureC: 20, referenceJunctionC: value })).toMatchObject({ value: false, error: expect.stringContaining("Type K") });
});

it("uses the same compensated signal in a wired comparator and coil, propagating faults without fallback actuation", () => {
  const document: CircuitDocument = {
    id: "type-k-control", name: "Compensated Type K threshold", description: "Thermocouple terminal EMF compared in mV", revision: 1,
    components: [
      { id: "tc", definitionId: "sensor.thermocouple", reference: "B1", x: 100, y: 100, rotation: 0, properties: { temperatureC: 500, referenceJunctionC: 0 } },
      { id: "compare", definitionId: "logic.comparator-greater-than", reference: "G1", x: 300, y: 100, rotation: 0, properties: { left: 100, right: 20.6 } },
      { id: "coil", definitionId: "logic.output-coil", reference: "K1", x: 500, y: 100, rotation: 0, properties: { input: true } },
    ],
    wires: [
      { id: "w1", from: { componentId: "tc", terminalId: "signal" }, to: { componentId: "compare", terminalId: "in-a" }, points: [] },
      { id: "w2", from: { componentId: "compare", terminalId: "out" }, to: { componentId: "coil", terminalId: "in" }, points: [] },
    ],
  };
  expect(validateCircuit(document, catalogById)).toEqual([]);
  const runs = () => executeCircuitModels(document, catalogById);
  expect(runs().find((run) => run.componentId === "coil")!.output.value).toBe("ON");
  document.components[0].properties.referenceJunctionC = 100;
  expect(runs().find((run) => run.componentId === "coil")!.output.value).toBe("OFF");
  document.components[0].properties.temperatureC = 2000;
  const failed = runs();
  for (const run of failed) expect(run.output.value).toContain("ERROR:");
  const coil = failed.find((run) => run.componentId === "coil")!;
  expect(evaluateFunctionalSignal(coil.modelId, coil.evaluatedProperties)).toMatchObject({ value: false, error: expect.stringContaining("Type K") });
  expect(document.components.every((c) => c.properties.runtimeSignalError === undefined)).toBe(true);
  document.components[0].properties = { temperatureC: 500, referenceJunctionC: 0 };
  expect(runs().find((run) => run.componentId === "coil")!.output.value).toBe("ON");
});

it("opens a wired contactor on a sensor fault even when its configured command is true", () => {
  const state = transitionReversing(transitionReversing(initialReversingState(), "close-breaker"), "start-forward");
  const document = applyReversingState(createReversingCircuit(), state);
  document.components.push(
    { id: "tc", definitionId: "sensor.thermocouple", reference: "B1", x: 100, y: 850, rotation: 0, properties: { temperatureC: 500 } },
    { id: "compare", definitionId: "logic.comparator-greater-than", reference: "G1", x: 300, y: 850, rotation: 0, properties: { left: 100, right: 0 } },
  );
  document.wires = document.wires.filter((wire) => !(wire.to.componentId === "forward" && wire.to.terminalId === "a1"));
  document.wires.push(
    { id: "tc-input", from: { componentId: "tc", terminalId: "signal" }, to: { componentId: "compare", terminalId: "in-a" }, points: [] },
    { id: "tc-command", from: { componentId: "compare", terminalId: "out" }, to: { componentId: "forward", terminalId: "a1" }, points: [] },
  );
  expect(validateCircuit(document, catalogById)).toEqual([]);
  expect(executeCircuitModels(document, catalogById).find((run) => run.reference === "M1")!.output.value).toContain("1440");
  document.components.find((c) => c.id === "tc")!.properties.temperatureC = 2000;
  const failed = executeCircuitModels(document, catalogById);
  expect(failed.find((run) => run.reference === "KM1")!.evaluatedProperties.energized).toBe(false);
  expect(failed.find((run) => run.reference === "M1")!.output.value).toBe("STANDBY");
});
